"""
Topic 01 - Variables and Data Types
Runnable examples matching the README.
"""

# Example 1: creating and printing variables
name = "Alice"
age = 25
print(name)
print(age)
# Expected output:
# Alice
# 25

# Example 2: checking types
height = 5.9
is_sunny = True
print(type(height))
print(type(is_sunny))
# Expected output:
# <class 'float'>
# <class 'bool'>

# Example 3: reassigning a variable
score = 10
print(score)
score = 20  # overwrites the old value
print(score)
# Expected output:
# 10
# 20

# Example 4: combining variables in output
name = "Bob"
age = 30
print(name, "is", age, "years old")
# Expected output: Bob is 30 years old
