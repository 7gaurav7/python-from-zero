# --- 01: Comprehensions ---
# 1. Build a list of cubes (n ** 3) for n from 1 to 10.

# 2. Given a list of words, build a list of only words longer than 4 chars.

# 3. Build a dictionary mapping each number 1-5 to its square.


# --- 02: Lambda Functions ---
# 4. Write a lambda that doubles a number, and call it on a few values.

# 5. Sort a list of tuples (name, age) by age using a lambda key.


# --- 03: map() and filter() ---
# 6. Use map() to square every number in a list.

# 7. Use filter() to keep only words longer than 3 letters.


# --- 04: *args and **kwargs ---
# 8. Write total(*args) returning the sum of any number of numbers.

# 9. Write print_all(**kwargs) printing every key-value pair.


# --- 05: enumerate() and zip() ---
# 10. Use enumerate() to print each item with its 1-based position.

# 11. Given names and emails lists, use zip() to print "name: email".


# --- 06: Unpacking ---
# 12. Unpack (name, age, city) into three variables and print them.

# 13. Given a list of 3+ numbers, unpack first, last, and "the rest".


# --- 07: Iterators ---
# 14. Manually iter()/next() a 4-item list to print items one at a time.


# --- 08: Generators ---
# 15. Write a generator count_up_to(n) yielding 1, 2, ..., n.

# 16. Write even_numbers_up_to(n) yielding even numbers 0 to n.


# --- 09: Decorators ---
# 17. Write log_calls printing a function's name each time it's called.

# 18. Write uppercase_result uppercasing whatever string a function returns.


