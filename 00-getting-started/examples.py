# Example 1: print text to the screen
print("Hello, World!")
# Expected output: Hello, World!

# Example 2: multiple lines run top to bottom, in order
print("Line 1")
print("Line 2")
print("Line 3")
# Expected output:
# Line 1
# Line 2
# Line 3

# Example 3: comments are ignored by Python
# Print a greeting
print("Good morning!")  # this comment is ignored too
# Expected output: Good morning!

# Example 4: Python can do arithmetic directly inside print()
print(2 + 3)
print(10 - 4)
# Expected output:
# 5
# 6
